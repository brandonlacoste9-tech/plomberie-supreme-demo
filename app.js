let lang = localStorage.getItem("sf-lang") || "fr";

function applyLang(l) {
  lang = l;
  localStorage.setItem("sf-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "fr" ? "EN" : "FR";
  document.title = l === "fr"
    ? "Plomberie Suprême — Plombier à Côte Saint-Luc | Débouchage, dégel, urgence 24h"
    : "Plomberie Suprême — Plumber in Côte Saint-Luc | Unclogging, thawing, 24h emergency";
}

